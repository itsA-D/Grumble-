//go:build ignore

// Command mapgen turns the Natural Earth 110m admin-0 countries GeoJSON into a
// committed Go file of SVG path data for the world map (FR-MAP-1).
//
// Usage:
//
//	go run scripts/mapgen/main.go -in scripts/mapgen/ne_110m_admin_0_countries.geojson \
//	    -out internal/service/mapsvc/geometry/geometry.go
//
// The output is deterministic so regenerating it on an unchanged dataset is a
// no-op in git. Natural Earth data is in the public domain; the source URL is
// recorded in the generated header and in docs/map-data.md.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"

	"grumble/internal/domain/taxonomy"
)

const (
	viewWidth  = 880.0
	viewHeight = 440.0
)

type featureCollection struct {
	Features []feature `json:"features"`
}

type feature struct {
	Properties properties `json:"properties"`
	Geometry   geometry   `json:"geometry"`
}

type properties struct {
	Name   string `json:"NAME"`
	NameEN string `json:"NAME_EN"`
	ISO2   string `json:"ISO_A2"`
	ISO2EH string `json:"ISO_A2_EH"`
}

type geometry struct {
	Type        string          `json:"type"`
	Coordinates json.RawMessage `json:"coordinates"`
}

type outCountry struct {
	ISO2   string
	Name   string
	PathD  string
	Region taxonomy.Region
}

func main() {
	in := flag.String("in", "scripts/mapgen/ne_110m_admin_0_countries.geojson", "Natural Earth GeoJSON input")
	out := flag.String("out", "internal/service/mapsvc/geometry/geometry.go", "generated Go output")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("read input: %v", err)
	}
	var fc featureCollection
	if err := json.Unmarshal(raw, &fc); err != nil {
		log.Fatalf("parse geojson: %v", err)
	}

	countries := make([]outCountry, 0, len(fc.Features))
	seen := map[string]bool{}
	for _, f := range fc.Features {
		iso := normalISO(f.Properties.ISO2, f.Properties.ISO2EH)
		if iso == "" || seen[iso] {
			continue
		}
		region := taxonomy.RegionOf(iso)
		if region == "" {
			continue
		}
		path := buildPath(f.Geometry)
		if path == "" {
			continue
		}
		name := f.Properties.NameEN
		if name == "" {
			name = f.Properties.Name
		}
		seen[iso] = true
		countries = append(countries, outCountry{ISO2: iso, Name: name, PathD: path, Region: region})
	}

	sort.Slice(countries, func(i, j int) bool { return countries[i].ISO2 < countries[j].ISO2 })

	var b strings.Builder
	b.WriteString("// Code generated by scripts/mapgen. DO NOT EDIT.\n")
	b.WriteString("// Source: Natural Earth 110m Admin-0 Countries (public domain)\n")
	b.WriteString("// https://www.naturalearthdata.com/downloads/110m-cultural-vectors/\n")
	b.WriteString("// Projection: equirectangular into an 880x440 viewBox.\n\n")
	b.WriteString("package geometry\n\n")
	b.WriteString("import \"grumble/internal/domain/taxonomy\"\n\n")
	b.WriteString("// CountryGeometry holds the SVG path data for a country.\n")
	b.WriteString("type CountryGeometry struct {\n")
	b.WriteString("\tISO2   string\n\tName   string\n\tPathD  string\n\tRegion taxonomy.Region\n}\n\n")
	b.WriteString("// AllCountries is the complete list of country geometries for the map,\n")
	b.WriteString("// sorted by ISO2 for deterministic output.\n")
	b.WriteString("var AllCountries = []CountryGeometry{\n")
	for _, c := range countries {
		fmt.Fprintf(&b, "\t{ISO2:%q, Name:%q, PathD:%q, Region:%q},\n", c.ISO2, c.Name, c.PathD, string(c.Region))
	}
	b.WriteString("}\n\n")
	b.WriteString("// CountryByISO2 returns the geometry for a country by its ISO2 code.\n")
	b.WriteString("func CountryByISO2(iso2 string) (CountryGeometry, bool) {\n")
	b.WriteString("\tfor _, c := range AllCountries {\n\t\tif c.ISO2 == iso2 {\n\t\t\treturn c, true\n\t\t}\n\t}\n")
	b.WriteString("\treturn CountryGeometry{}, false\n}\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatalf("write output: %v", err)
	}

	var total int
	for _, c := range countries {
		total += len(c.PathD)
	}
	log.Printf("generated %d countries, %d bytes of path data -> %s", len(countries), total, *out)
}

// normalISO picks the first real ISO alpha-2 code, ignoring Natural Earth's
// "-99" placeholder used for disputed or partially recognised territories.
func normalISO(primary, fallback string) string {
	for _, v := range []string{primary, fallback} {
		v = strings.TrimSpace(v)
		if len(v) == 2 && v != "-9" && v[0] >= 'A' && v[0] <= 'Z' && v[1] >= 'A' && v[1] <= 'Z' {
			return v
		}
	}
	return ""
}

// buildPath converts Polygon or MultiPolygon coordinates into one SVG path.
func buildPath(g geometry) string {
	var rings [][][2]float64
	switch g.Type {
	case "Polygon":
		rings = append(rings, decodePolygon(g.Coordinates)...)
	case "MultiPolygon":
		var polys [][][][2]float64
		if err := json.Unmarshal(g.Coordinates, &polys); err != nil {
			return ""
		}
		for _, p := range polys {
			rings = append(rings, p...)
		}
	default:
		return ""
	}

	var sb strings.Builder
	for _, ring := range rings {
		if len(ring) < 4 {
			continue
		}
		pts := project(ring)
		pts = simplify(pts)
		if len(pts) < 3 {
			continue
		}
		fmt.Fprintf(&sb, "M%s", formatPoint(pts[0]))
		for _, p := range pts[1:] {
			fmt.Fprintf(&sb, "L%s", formatPoint(p))
		}
		sb.WriteString("Z")
	}
	return sb.String()
}

func decodePolygon(raw json.RawMessage) [][][2]float64 {
	var polys [][][2]float64
	if err := json.Unmarshal(raw, &polys); err != nil {
		return nil
	}
	return polys
}

// project maps lon/lat degrees to the 880x440 viewBox (equirectangular).
func project(ring [][2]float64) [][2]float64 {
	out := make([][2]float64, 0, len(ring))
	for _, c := range ring {
		lon, lat := c[0], c[1]
		x := (lon + 180) / 360 * viewWidth
		y := (90 - lat) / 180 * viewHeight
		out = append(out, [2]float64{round1(x), round1(y)})
	}
	return out
}

// simplify drops repeated and collinear points. The dataset is already
// generalised to 110m, so this mostly removes redundant vertices on straight
// coastlines and cuts the committed file size without a visible change.
func simplify(pts [][2]float64) [][2]float64 {
	if len(pts) < 3 {
		return pts
	}
	dedup := make([][2]float64, 0, len(pts))
	for _, p := range pts {
		if len(dedup) == 0 || dedup[len(dedup)-1] != p {
			dedup = append(dedup, p)
		}
	}
	if len(dedup) > 1 && dedup[0] == dedup[len(dedup)-1] {
		dedup = dedup[:len(dedup)-1]
	}

	out := make([][2]float64, 0, len(dedup))
	for i, p := range dedup {
		prev := dedup[(i-1+len(dedup))%len(dedup)]
		next := dedup[(i+1)%len(dedup)]
		if collinear(prev, p, next) {
			continue
		}
		out = append(out, p)
	}
	if len(out) < 3 {
		return dedup
	}
	return out
}

func collinear(a, b, c [2]float64) bool {
	cross := (b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0])
	return math.Abs(cross) < 0.02
}

func round1(v float64) float64 {
	return math.Round(v*10) / 10
}

func formatPoint(p [2]float64) string {
	return trimNum(p[0]) + " " + trimNum(p[1])
}

func trimNum(v float64) string {
	s := strconv.FormatFloat(v, 'f', 1, 64)
	s = strings.TrimSuffix(s, ".0")
	return s
}
